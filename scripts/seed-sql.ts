/**
 * Builds supabase/seed.sql from the typed seed content in src/data.
 * The bundled dataset stays the single source of truth; the SQL is generated, never hand-edited.
 */
import { achievements } from '../src/data/achievements';
import { levels, modules } from '../src/data/curriculum';
import { exercises } from '../src/data/exercises';
import { grammarTopics } from '../src/data/grammar';
import { lessons } from '../src/data/lessons';
import { vocabulary, vocabularyTopics } from '../src/data/vocabulary';
import type { Question } from '../src/types/content';

type SqlValue = string | number | boolean | null | string[] | { json: unknown };

const lit = (v: SqlValue): string => {
  if (v === null) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) return v.length ? `array[${v.map(lit).join(', ')}]::text[]` : `'{}'::text[]`;
  if (typeof v === 'object') return `${lit(JSON.stringify(v.json))}::jsonb`;
  return `'${v.replaceAll("'", "''")}'`;
};

function upsert(table: string, rows: Record<string, SqlValue>[], conflict: string[]): string {
  if (rows.length === 0) return '';
  const cols = Object.keys(rows[0]!);
  const updates = cols.filter((c) => !conflict.includes(c));
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c] ?? null)).join(', ')})`).join(',\n');
  const onConflict = updates.length
    ? `on conflict (${conflict.join(', ')}) do update set ${updates.map((c) => `${c} = excluded.${c}`).join(', ')}`
    : `on conflict (${conflict.join(', ')}) do nothing`;
  return `insert into public.${table} (${cols.join(', ')}) values\n${values}\n${onConflict};\n`;
}

/** Type-specific question data stored in questions.payload. */
function questionPayload(q: Question): Record<string, unknown> {
  switch (q.type) {
    case 'multiple_choice':
      return {}; // options live in answer_options
    case 'true_false':
      return { statement: q.statement, answer: q.answer };
    case 'fill_blank':
      return { sentence: q.sentence, acceptedAnswers: q.acceptedAnswers };
    case 'error_correction':
      return { sentence: q.sentence, acceptedAnswers: q.acceptedAnswers };
    case 'translation':
      return { sourceVi: q.sourceVi, acceptedAnswers: q.acceptedAnswers };
    case 'matching':
      return { pairs: q.pairs };
    case 'ordering':
      return { tokens: q.tokens };
  }
}

export function buildSeedSql(): string {
  const parts: string[] = [
    '-- GENERATED by `npm run db:seed:generate` from src/data. Do not edit by hand.',
    '-- Idempotent: safe to run repeatedly (upserts by primary key).',
    'begin;',
  ];

  parts.push(
    upsert(
      'cefr_levels',
      levels.map((l) => ({ id: l.id, name: l.name, name_vi: l.nameVi, description: l.description, sort_order: l.order })),
      ['id'],
    ),
  );

  parts.push(
    upsert(
      'modules',
      modules.map((m) => ({
        id: m.id, level_id: m.levelId, title: m.title, title_vi: m.titleVi, description: m.description, category: m.category, sort_order: m.order,
      })),
      ['id'],
    ),
  );

  parts.push(
    upsert(
      'lessons',
      lessons.map((l) => ({
        id: l.id, module_id: l.moduleId, level_id: l.levelId, title: l.title, title_vi: l.titleVi, description: l.description,
        objectives: l.objectives, estimated_minutes: l.estimatedMinutes, sort_order: l.order,
        vocabulary_ids: l.vocabularyIds, exercise_ids: l.exerciseIds,
      })),
      ['id'],
    ),
  );

  // Blocks are replaced wholesale so removed blocks disappear on re-seed.
  parts.push(`delete from public.lesson_contents where lesson_id in (${lessons.map((l) => lit(l.id)).join(', ')});\n`);
  parts.push(
    upsert(
      'lesson_contents',
      lessons.flatMap((l) => l.blocks.map((block, position) => ({ lesson_id: l.id, position, block: { json: block } }))),
      ['lesson_id', 'position'],
    ),
  );

  parts.push(
    upsert(
      'grammar_topics',
      grammarTopics.map((g) => ({
        id: g.id, level_id: g.level, title: g.title, title_vi: g.titleVi, summary_vi: g.summaryVi, lesson_id: g.lessonId, sort_order: g.order,
      })),
      ['id'],
    ),
  );

  parts.push(upsert('vocabulary_topics', vocabularyTopics.map((t) => ({ id: t.id, name: t.name, name_vi: t.nameVi })), ['id']));
  parts.push(
    upsert(
      'vocabulary',
      vocabulary.map((v) => ({
        id: v.id, word: v.word, ipa: v.ipa, part_of_speech: v.partOfSpeech, level_id: v.level, topic_id: v.topic, definition: v.definition,
        meaning_vi: v.meaningVi, example: v.example, example_vi: v.exampleVi, synonyms: v.synonyms, antonyms: v.antonyms, collocations: v.collocations,
      })),
      ['id'],
    ),
  );

  parts.push(
    upsert(
      'exercises',
      exercises.map((e) => ({
        id: e.id, level_id: e.level, skill: e.skill, title: e.title, title_vi: e.titleVi, description: e.description, estimated_minutes: e.estimatedMinutes,
      })),
      ['id'],
    ),
  );
  parts.push(`delete from public.questions where exercise_id in (${exercises.map((e) => lit(e.id)).join(', ')});\n`);
  parts.push(
    upsert(
      'questions',
      exercises.flatMap((e) =>
        e.questions.map((q, position) => ({
          id: `${e.id}:${q.id}`, exercise_id: e.id, position, type: q.type, prompt: q.prompt, context: q.context ?? null,
          payload: { json: questionPayload(q) }, explanation_vi: q.explanationVi,
        })),
      ),
      ['id'],
    ),
  );
  parts.push(
    upsert(
      'answer_options',
      exercises.flatMap((e) =>
        e.questions.flatMap((q) =>
          q.type === 'multiple_choice'
            ? q.options.map((o, position) => ({
                question_id: `${e.id}:${q.id}`, option_key: o.id, text: o.text, is_correct: o.id === q.correctOptionId, position,
              }))
            : [],
        ),
      ),
      ['question_id', 'option_key'],
    ),
  );

  parts.push(
    upsert(
      'achievements',
      achievements.map((a) => ({ id: a.id, title: a.title, description: a.description, metric: a.metric, goal: a.goal })),
      ['id'],
    ),
  );

  parts.push('commit;');
  return parts.filter(Boolean).join('\n');
}
